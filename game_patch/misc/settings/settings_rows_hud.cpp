void apply_big_hud()
{
    // Same guard the bighud command and hud_init apply: big HUD needs at least 1024x768.
    if (g_alpine_game_config.big_hud && is_screen_resolution_too_low_for_big_hud()) {
        return;
    }
    set_big_hud(g_alpine_game_config.big_hud);
}

bool damage_flash_offered(const int value)
{
    return value != 2 || is_d3d11();
}

